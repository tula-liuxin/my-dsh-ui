#!/usr/bin/env node
/**
 * Generate the sub-plugin table inside `client.js` from the `subplugins/` directory.
 *
 * A sub-plugin directory holds `subplugin.json` (manifest) and `client.js` (UI half).
 * The UI half is plain ESM-free source with exactly these top-level exports:
 *   export const meta = { ... }          // optional extra UI metadata
 *   export function apply(ui) { ... }    // required: mounts the contribution
 *
 * The browser cannot import files from a package directory at runtime, so bundled
 * sub-plugins are inlined into the generated region of `client.js`. Run
 * `node scripts/build.mjs` after adding, editing or removing a sub-plugin.
 *
 * Usage: node scripts/build.mjs [--check]
 *   --check  exit 1 when client.js is out of date instead of rewriting it
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SUBPLUGINS_DIR = join(ROOT, 'subplugins');
const CLIENT_FILE = join(ROOT, 'client.js');
const START = '/* my-dsh-ui:subplugins:start — generated by scripts/build.mjs, do not edit by hand */';
const END = '/* my-dsh-ui:subplugins:end */';
const checkOnly = process.argv.includes('--check');

const forbidden = /^\s*(?:import|export)\b/gm;

/** Turn one sub-plugin's UI source into a factory body for the Client bundle. */
function compileClientSource(source, id) {
  const allowedExport = /^\s*export\s+(?:function\s+apply|const\s+meta)\b/gm;
  const leftovers = [...(source.match(forbidden) ?? [])].length - [...(source.match(allowedExport) ?? [])].length;
  if (leftovers > 0) {
    throw new Error(`${id}/client.js may only use "export function apply(ui)" and "export const meta": no import/export statements`);
  }
  return source
    .replace(/^\s*export\s+function\s+apply\b/gm, 'function apply')
    .replace(/^\s*export\s+const\s+meta\b/gm, 'const meta');
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : pad + line))
    .join('\n');
}

async function listDirs(dir) {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
  } catch {
    return [];
  }
}

async function buildBlock() {
  const blocks = [];
  for (const dirName of await listDirs(SUBPLUGINS_DIR)) {
    const dir = join(SUBPLUGINS_DIR, dirName);
    let manifest;
    try {
      manifest = JSON.parse(await readFile(join(dir, 'subplugin.json'), 'utf8'));
    } catch {
      throw new Error(`subplugins/${dirName}: missing or invalid subplugin.json`);
    }
    const id = typeof manifest.id === 'string' && manifest.id !== '' ? manifest.id : dirName;
    if (dirName !== id) throw new Error(`subplugins/${dirName}: directory name must equal manifest id "${id}"`);
    let source;
    try {
      source = await readFile(join(dir, 'client.js'), 'utf8');
    } catch {
      source = 'function apply() {}\n';
    }
    const compiled = compileClientSource(source, id);
    blocks.push(
      [
        '  {',
        `    id: ${JSON.stringify(id)},`,
        `    manifest: ${JSON.stringify({ ...manifest, id }, null, 2).replace(/\n/g, '\n    ')},`,
        '    create(ui) {',
        indent(compiled.trimEnd(), 6),
        '      return typeof apply === "function" ? apply(ui) : undefined;',
        '    },',
        '  },',
      ].join('\n'),
    );
  }
  return [START, 'const SUBPLUGINS = [', ...blocks, '];', END].join('\n');
}

/** Replace the generated region, or validate it. */
function spliceClient(text, block) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('client.js is missing the my-dsh-ui:subplugins markers');
  }
  return `${text.slice(0, start)}${block}${text.slice(end + END.length)}`;
}

const current = await readFile(CLIENT_FILE, 'utf8');
const next = spliceClient(current, await buildBlock());

if (checkOnly) {
  if (next !== current) {
    console.error('client.js is stale: run node scripts/build.mjs');
    process.exit(1);
  }
  console.log('client.js sub-plugin table is up to date');
} else if (next === current) {
  console.log('client.js sub-plugin table is already up to date');
} else {
  await writeFile(CLIENT_FILE, next);
  console.log('client.js sub-plugin table regenerated');
}
